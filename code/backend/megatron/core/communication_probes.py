"""Low-overhead communication counters shared by Megatron core and training.

CUDA event pairs are recorded at the actual asynchronous wait sites and are
resolved only at the normal logging boundary, after the interval timer has
synchronized the device. This preserves communication/computation overlap.
"""

from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass

import torch


@dataclass
class _CudaInterval:
    name: str
    start: torch.cuda.Event
    end: torch.cuda.Event


_enabled = False
_counters: dict[str, float] = defaultdict(float)
_carried: dict[str, float] = defaultdict(float)
_intervals: list[_CudaInterval] = []
_open_intervals: dict[object, tuple[str, torch.cuda.Event]] = {}


def configure(enabled: bool) -> None:
    """Enable or disable collection and discard any stale window state."""

    global _enabled
    _enabled = bool(enabled)
    reset()


def enabled() -> bool:
    return _enabled


def increment(name: str, value: float = 1.0) -> None:
    """Add a scalar counter without synchronizing CUDA."""

    if _enabled:
        _counters[name] += float(value)


def record_collective(name: str, payload_bytes: int, calls: int = 1) -> None:
    """Record logical collective count and full input-buffer bytes."""

    if not _enabled:
        return
    _counters[f"{name}_calls"] += int(calls)
    _counters[f"{name}_buffer_bytes"] += int(payload_bytes)


def start_cuda_interval():
    """Record a start event, or return ``None`` when probes are disabled."""

    if not _enabled:
        return None
    event = torch.cuda.Event(enable_timing=True)
    event.record()
    return event


def finish_cuda_interval(name: str, start) -> None:
    """Record the end of a CUDA interval without waiting for it."""

    if start is None:
        return
    end = torch.cuda.Event(enable_timing=True)
    end.record()
    _intervals.append(_CudaInterval(name=name, start=start, end=end))


def begin_open_cuda_interval(name: str, key: object) -> None:
    """Start an interval that may be closed by a later step or log boundary."""

    if not _enabled:
        return
    if key in _open_intervals:
        raise RuntimeError(f"communication probe interval is already open: {key!r}")
    start = start_cuda_interval()
    assert start is not None
    _open_intervals[key] = (name, start)


def finish_open_cuda_interval(key: object) -> None:
    """Close a previously opened interval, if it is still active."""

    entry = _open_intervals.pop(key, None)
    if entry is None:
        return
    name, start = entry
    finish_cuda_interval(name, start)


def _close_open_intervals() -> None:
    first_new_interval = len(_intervals)
    for key in list(_open_intervals):
        finish_open_cuda_interval(key)
    # These end events were recorded after the caller's normal log-boundary
    # synchronization. Complete only the newly closed events before reading
    # elapsed_time; ordinary in-step intervals remain fully deferred.
    for interval in _intervals[first_new_interval:]:
        interval.end.synchronize()


def snapshot(reset_window: bool = True) -> dict[str, float]:
    """Return accumulated counters and CUDA durations in seconds.

    The caller must invoke this only after prior device work has completed.
    Megatron's log boundary satisfies that requirement via ``interval-time``.
    """

    _close_open_intervals()
    values = dict(_carried)
    for name, value in _counters.items():
        values[name] = values.get(name, 0.0) + value
    for interval in _intervals:
        values[f"{interval.name}_seconds"] = values.get(
            f"{interval.name}_seconds", 0.0
        ) + interval.start.elapsed_time(interval.end) / 1000.0
        values[f"{interval.name}_events"] = values.get(
            f"{interval.name}_events", 0.0
        ) + 1.0
    if reset_window:
        reset()
    return values


def carry_active_window() -> None:
    """Preserve completed training events while a non-training section runs."""

    if not _enabled:
        return
    _close_open_intervals()
    values = dict(_counters)
    for interval in _intervals:
        values[f"{interval.name}_seconds"] = values.get(
            f"{interval.name}_seconds", 0.0
        ) + interval.start.elapsed_time(interval.end) / 1000.0
        values[f"{interval.name}_events"] = values.get(
            f"{interval.name}_events", 0.0
        ) + 1.0
    for name, value in values.items():
        _carried[name] += value
    _counters.clear()
    _intervals.clear()
    _open_intervals.clear()


def discard_active_window() -> None:
    """Discard communication generated by eval/checkpoint work."""

    _counters.clear()
    _intervals.clear()
    _open_intervals.clear()


def reset() -> None:
    """Discard the current counter window."""

    _counters.clear()
    _carried.clear()
    _intervals.clear()
    _open_intervals.clear()


